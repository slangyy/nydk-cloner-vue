function validateSpaceHotspotConfig(slides: readonly SpaceSlide[]): void {
  const imageIds = new Set<string>();
  const hotspotIds = new Set<string>();

  const registerImage = (id: string, src: string, thumbnail: string): void => {
    if (imageIds.has(id)) {
      throw new Error(`Duplicate space gallery image id: ${id}`);
    }
    imageIds.add(id);
    if (!src.startsWith("/assets/") || !thumbnail.startsWith("/assets/")) {
      throw new Error(`Space gallery image ${id} must use local asset paths`);
    }
  };

  slides.forEach((slide) => {
    slide.gallery.forEach((image) => {
      registerImage(image.id, image.src, image.thumbnail);
      image.children?.forEach((hotspot) => {
        if (hotspotIds.has(hotspot.id)) {
          throw new Error(`Duplicate space gallery hotspot id: ${hotspot.id}`);
        }
        hotspotIds.add(hotspot.id);
        const { x, y } = hotspot.position;
        if (!Number.isFinite(x) || !Number.isFinite(y) || x < 0 || x > 100 || y < 0 || y > 100) {
          throw new Error(`Space gallery hotspot ${hotspot.id} must use 0-100 coordinates`);
        }
        if (hotspot.images.length === 0) {
          throw new Error(`Space gallery hotspot ${hotspot.id} must contain detail images`);
        }
        hotspot.images.forEach((detailImage) => {
          registerImage(detailImage.id, detailImage.src, detailImage.thumbnail);
        });
      });
    });
  });
}

